import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const {OfflineAudioContext}=eval(readFileSync('crates/pyro-webapi/src/webaudio.js','utf8'))({});
const c=new OfflineAudioContext(3,128,44100);
const s=c.createBufferSource(),v=c.createConstantSource(),g=c.createGain();
s.buffer=c.createBuffer(2,128,44100);
s.buffer.getChannelData(0).fill(.25);s.buffer.getChannelData(1).fill(.5);
v.offset.value=1;g.gain.value=0;
const split=c.createChannelSplitter(3),merge=c.createChannelMerger(3);
s.connect(split);split.connect(merge,1,0);split.connect(merge,2,1);
split.connect(g.gain,1);split.connect(g.gain,0);split.disconnect(g.gain,1);
v.connect(g).connect(merge,0,2);merge.connect(c.destination);
s.start();v.start();
const buf=await c.startRendering();
assert.deepEqual([0,1,2].map(i=>buf.getChannelData(i)[3]),[.5,0,.25]);
console.log('Output port selection, silent channels, simultaneous modulation routes and selective disconnect passed.');
const ctx=new OfflineAudioContext(1,128,44100),sp=ctx.createChannelSplitter(2),gain=ctx.createGain();
sp.connect(gain.gain,0);sp.connect(gain.gain,1);
sp.disconnect(gain.gain,undefined);
assert.throws(()=>sp.disconnect(gain.gain,0),{name:'InvalidAccessError'});
assert.throws(()=>sp.disconnect(gain.gain,1,0),TypeError);
let reads=0;sp.disconnect(gain.gain,{valueOf(){reads++;return 1}});
assert.equal(reads,1);
console.log('Explicit undefined, overload selection and single conversion passed.');
