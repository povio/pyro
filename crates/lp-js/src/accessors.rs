//! WebIDL attributes as JavaScriptCore custom accessors.
//!
//! A prototype accessor whose getter is an ordinary function object costs a
//! JavaScript call frame and, for a C API function object, JSC's unlinkable
//! host-call slow path on every read: about 300 ns for `node.parentElement`,
//! which Playwright's selector engine reads tens of thousands of times per
//! locator. The patched JSC (`JSObjectSetCustomAccessor`) installs an attribute
//! as a `CustomGetterSetter` instead: an inline cache calls the getter's C
//! function pointer directly with the receiver, and the property still reads
//! as `{get, set, enumerable, configurable}` from `getOwnPropertyDescriptor`.
//!
//! JSC passes no data to a custom getter, so each attribute gets a trampoline
//! of its own (generated by `build.rs`), which forwards its slot number to the
//! dispatcher here. Slots are process-wide, keyed by the class type and the
//! attribute name: every engine registers the same (class, name) with the same
//! callbacks, so the first registration's entry serves them all.
use crate::class::{guard, GetterResult, Header, InvokeHFn, Kind, MemberCall, PayloadTag};
use crate::error::JsError;
use crate::value::Args;
use lp_jsc_sys as sys;
use std::any::TypeId;
use std::collections::HashMap;
use std::ffi::c_void;
use std::panic::{catch_unwind, AssertUnwindSafe};
use std::ptr;
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::sync::Mutex;

include!(concat!(env!("OUT_DIR"), "/accessor_trampolines.rs"));

/// A slot's getter or setter: the two words of a [`MemberCall`], written once
/// before the first call through the slot.
struct SlotCall {
    invoke: AtomicUsize,
    f: AtomicUsize,
}

impl SlotCall {
    const EMPTY: SlotCall = SlotCall { invoke: AtomicUsize::new(0), f: AtomicUsize::new(0) };

    fn store(&self, call: MemberCall) {
        self.f.store(call.f as usize, Ordering::Relaxed);
        self.invoke.store(call.invoke as usize, Ordering::Release);
    }

    fn clear(&self) {
        self.invoke.store(0, Ordering::Release);
    }

    fn load(&self) -> Option<MemberCall> {
        let invoke = self.invoke.load(Ordering::Acquire);
        if invoke == 0 {
            return None;
        }
        // SAFETY: stored from a `MemberCall` by `store`, which writes `f`
        // before publishing `invoke`.
        Some(MemberCall {
            invoke: unsafe { std::mem::transmute::<usize, crate::class::InvokeFn>(invoke) },
            f: self.f.load(Ordering::Relaxed) as *const (),
        })
    }
}

static GETTER_CALLS: [SlotCall; SLOTS] = [const { SlotCall::EMPTY }; SLOTS];
static SETTER_CALLS: [SlotCall; SLOTS] = [const { SlotCall::EMPTY }; SLOTS];
/// Getters that take the lean dispatch (`ClassDef::pure_getter`).
static PURE: [AtomicBool; SLOTS] = [const { AtomicBool::new(false) }; SLOTS];
/// What each pure getter returns (`sys::spi::kJSFastGetterResult*`).
static RESULT: [AtomicUsize; SLOTS] = [const { AtomicUsize::new(0) }; SLOTS];
/// Each pure getter's invoker from a payload header (`InvokeHFn`; 0: none).
static GETTER_H: [AtomicUsize; SLOTS] = [const { AtomicUsize::new(0) }; SLOTS];

/// Attributes that found no free slot (see [`slot_usage`]).
static OVERFLOWED: AtomicUsize = AtomicUsize::new(0);

/// Custom accessor slots in use, and the attributes that found none and were
/// installed as ordinary accessors (slower: no direct inline cache call).
pub fn slot_usage() -> (usize, usize) {
    let used = SLOT_TABLE.lock().unwrap_or_else(|e| e.into_inner()).as_ref().map_or(0, |t| t.len());
    (used, OVERFLOWED.load(Ordering::Relaxed))
}

/// Slot numbers by (class type, attribute name).
static SLOT_TABLE: Mutex<Option<HashMap<(TypeId, &'static str), u16>>> = Mutex::new(None);

/// Whether the running JavaScriptCore installs custom accessors.
pub(crate) fn supported() -> bool {
    let spi = sys::spi::get();
    spi.set_custom_accessor.is_some() && spi.throw_exception.is_some()
}

/// The slot of the attribute `name` of class `class`, allocated on first use
/// with its callbacks; `None` once the slots are exhausted (the attribute is
/// then installed as an ordinary accessor).
pub(crate) fn slot_for(
    class: TypeId,
    name: &'static str,
    get: MemberCall,
    set: Option<MemberCall>,
    pure: bool,
    result: GetterResult,
    get_h: Option<InvokeHFn>,
) -> Option<u16> {
    if !supported() {
        return None;
    }
    let mut table = SLOT_TABLE.lock().unwrap_or_else(|e| e.into_inner());
    let table = table.get_or_insert_with(HashMap::new);
    // A class that defines an attribute twice (shared members, then its own)
    // gets the later definition, as the prototype property it installs last.
    let slot = match table.get(&(class, name)) {
        Some(&slot) => usize::from(slot),
        None if table.len() >= SLOTS => {
            OVERFLOWED.fetch_add(1, Ordering::Relaxed);
            return None;
        }
        None => table.len(),
    };
    GETTER_CALLS[slot].store(get);
    match set {
        Some(set) => SETTER_CALLS[slot].store(set),
        None => SETTER_CALLS[slot].clear(),
    }
    GETTER_H[slot].store(get_h.map_or(0, |f| f as usize), Ordering::Release);
    PURE[slot].store(pure, Ordering::Release);
    RESULT[slot].store(
        match result {
            GetterResult::Any => sys::spi::kJSFastGetterResultAny,
            GetterResult::Number => sys::spi::kJSFastGetterResultNumber,
            GetterResult::Boolean => sys::spi::kJSFastGetterResultBoolean,
            GetterResult::String => sys::spi::kJSFastGetterResultString,
            GetterResult::ObjectOrNull => sys::spi::kJSFastGetterResultObjectOrNull,
        } as usize,
        Ordering::Release,
    );
    table.insert((class, name), slot as u16);
    Some(slot as u16)
}

/// The receiver a custom accessor got, as the object the member runs on:
/// undefined and null stand for the global (as `toThis` makes them for a
/// function called that way; JSC gives custom accessors the raw receiver),
/// a cell (an object, or a string, symbol or bigint cell, which the brand
/// check then refuses) is itself, and any other immediate is no receiver.
/// Decoded without entering JSC: 64-bit JSC tags doubles and the other
/// immediates in the top bits or bit 1.
fn receiver(v: sys::JSValueRef) -> Option<sys::JSObjectRef> {
    const NOT_CELL_MASK: usize = 0xfffe_0000_0000_0000 | 0x2;
    const UNDEFINED: usize = 0xa;
    const NULL: usize = 0x2;
    let bits = v as usize;
    if bits == UNDEFINED || bits == NULL {
        return Some(ptr::null_mut());
    }
    (bits != 0 && bits & NOT_CELL_MASK == 0).then_some(v as sys::JSObjectRef)
}

/// Throws `exception` in `ctx` (JavaScript of `ctx` is on the stack).
unsafe fn throw(ctx: sys::JSContextRef, exception: sys::JSValueRef) {
    if let Some(f) = sys::spi::get().throw_exception {
        unsafe { f(ctx, exception) };
    }
}

/// Whether `slot` is a pure getter, and what it returns (for
/// `JSObjectSetFastGetter`).
pub(crate) fn pure_result(slot: u16) -> Option<std::os::raw::c_int> {
    PURE[usize::from(slot)].load(Ordering::Acquire).then(|| RESULT[usize::from(slot)].load(Ordering::Acquire) as _)
}

/// The JITs' entry to a pure getter (`JSObjectSetFastGetter`): the receiver
/// is a wrapper object already and `private_data` its payload header;
/// `context` is the slot. Falls back to the full dispatch like
/// [`lean_getter`].
pub(crate) unsafe extern "C" fn fast_getter_dispatch(
    ctx: sys::JSContextRef,
    this: sys::JSObjectRef,
    private_data: *mut c_void,
    context: *mut c_void,
) -> sys::JSValueRef {
    let slot = context as usize;
    if let Some(v) = unsafe { lean_getter_h(slot, private_data as *mut Header) } {
        return v;
    }
    unsafe { custom_getter_dispatch(slot, ctx, this as sys::JSValueRef, ptr::null()) }
}

/// The lean dispatch of a pure getter (`ClassDef::pure_getter`) on the
/// payload header `h` of its receiver: the scope is the receiver's realm
/// (kept by the payload), so nothing here reads thread-local state or enters
/// JavaScriptCore before the getter runs. No nesting depth, no termination
/// bookkeeping, no post-callback hook: those exist for callbacks that can run
/// script or mutate. `None` sends the call through the full dispatch: not a
/// wrapper instance, a disposed realm, an error, a panic.
#[inline]
unsafe fn lean_getter_h(slot: usize, h: *mut Header) -> Option<sys::JSValueRef> {
    unsafe {
        if h.is_null() || (*h).tag != PayloadTag::Wrapper || (*h).kind != Kind::Instance {
            return None;
        }
        let invoke = GETTER_H[slot].load(Ordering::Relaxed);
        if invoke == 0 {
            return None;
        }
        // SAFETY: stored from an `InvokeHFn` by `slot_for`.
        let invoke = std::mem::transmute::<usize, InvokeHFn>(invoke);
        let f = GETTER_CALLS[slot].f.load(Ordering::Relaxed) as *const ();
        let realm = (*h).realm_ref.upgrade()?;
        let ctx = realm.ctx.get() as sys::JSContextRef;
        if ctx.is_null() {
            return None;
        }
        let scope = crate::realm::Scope::new(ctx, &realm);
        match catch_unwind(AssertUnwindSafe(|| invoke(&scope, h, f))) {
            Ok(Ok(v)) if !v.is_null() => Some(v),
            _ => None,
        }
    }
}

/// [`lean_getter_h`] for the custom accessor entry, which gets the receiver
/// as a value: a wrapper cell's private data is its header.
unsafe fn lean_getter(slot: usize, this: sys::JSValueRef) -> Option<sys::JSValueRef> {
    let this = receiver(this)?;
    if this.is_null() {
        return None;
    }
    unsafe { lean_getter_h(slot, sys::JSObjectGetPrivate(this) as *mut Header) }
}

unsafe fn custom_getter_dispatch(
    slot: usize,
    ctx: sys::JSContextRef,
    this: sys::JSValueRef,
    _uid: *const c_void,
) -> sys::JSValueRef {
    if PURE[slot].load(Ordering::Relaxed) {
        if let Some(v) = unsafe { lean_getter(slot, this) } {
            return v;
        }
    }
    unsafe {
        let mut exc: sys::JSValueRef = ptr::null();
        let result = guard(ctx, &mut exc, ptr::null(), |scope| {
            let Some(call) = GETTER_CALLS[slot].load() else { return Err(JsError::Type("Illegal invocation".into())) };
            let Some(this) = receiver(this) else { return Err(JsError::Type("Illegal invocation".into())) };
            (call.invoke)(scope, this, Args::from_raw(ctx, 0, ptr::null()), call.f)
        });
        if !exc.is_null() {
            throw(ctx, exc);
            return sys::JSValueMakeUndefined(ctx);
        }
        if result.is_null() {
            return sys::JSValueMakeUndefined(ctx);
        }
        result
    }
}

unsafe fn custom_setter_dispatch(
    slot: usize,
    ctx: sys::JSContextRef,
    this: sys::JSValueRef,
    value: sys::JSValueRef,
    _uid: *const c_void,
) -> bool {
    unsafe {
        let mut exc: sys::JSValueRef = ptr::null();
        let stands = guard(ctx, &mut exc, false, |scope| {
            let Some(call) = SETTER_CALLS[slot].load() else { return Err(JsError::Type("Illegal invocation".into())) };
            let Some(this) = receiver(this) else { return Err(JsError::Type("Illegal invocation".into())) };
            (call.invoke)(scope, this, Args::from_raw(ctx, 1, &value), call.f)?;
            Ok(true)
        });
        if !exc.is_null() {
            throw(ctx, exc);
            return false;
        }
        stands
    }
}
